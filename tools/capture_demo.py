"""Record the README demo against an auth-disabled synthetic-data instance."""

import asyncio
import re
from pathlib import Path

from playwright.async_api import async_playwright, expect


async def main() -> None:
    output = Path("demo-capture")
    output.mkdir(exist_ok=True)
    async with async_playwright() as playwright:
        browser = await playwright.chromium.launch(headless=True)
        context = await browser.new_context(
            viewport={"width": 1280, "height": 800},
            record_video_dir=output,
            record_video_size={"width": 1280, "height": 800},
        )
        page = await context.new_page()
        page.set_default_timeout(5000)
        await page.goto("http://127.0.0.1:18080/", wait_until="networkidle")
        await page.wait_for_timeout(1200)
        await page.locator('[data-tab="collections"]').click()
        await page.locator('#collections form[action="/collections"] input[name="name"]').fill("Christmas")
        await page.locator('#collections form[action="/collections"] textarea').fill("Festive pre-rolls for December")
        await page.locator('#collections form[action="/collections"] input[name="color"]').fill("#b91c1c")
        await page.locator('#collections form[action="/collections"] button.primary').click()
        await expect(page.locator('#collections')).to_have_class(re.compile("active"))
        await page.wait_for_timeout(900)
        await page.locator('.collection-row:has-text("Christmas") [data-add-members]').click()
        await page.locator('[data-member-search]').fill("Christmas")
        await page.locator('#add-members-dialog input[value="Christmas"]').check()
        await page.locator('#add-members-dialog button.primary').click()
        await expect(page.locator('#collections')).to_have_class(re.compile("active"))
        await page.wait_for_timeout(1000)
        await page.locator('[data-tab="schedule"]').click()
        schedule_form = page.locator('#schedule form[action="/schedules"]')
        await schedule_form.locator('input[name="name"]').fill("Christmas")
        christmas_value = await schedule_form.locator('select[name="collection_id"] option', has_text="Christmas").get_attribute("value")
        await schedule_form.locator('select[name="collection_id"]').select_option(christmas_value)
        await schedule_form.locator('input[name="starts_at"]').fill("2026-12-01T00:00")
        await schedule_form.locator('input[name="ends_at"]').fill("2027-01-01T00:00")
        await schedule_form.locator('[data-recurrence]').select_option("custom")
        await schedule_form.locator('[data-rrule]').fill("FREQ=YEARLY;BYMONTH=12;BYMONTHDAY=1")
        await page.wait_for_timeout(700)
        await schedule_form.locator('[data-recurrence]').select_option("FREQ=YEARLY")
        await schedule_form.locator('input[name="color"]').fill("#ef4444")
        await schedule_form.locator('button.primary').click()
        await expect(page.locator('#schedule')).to_have_class(re.compile("active"))
        await page.wait_for_timeout(900)
        await page.locator('[data-calendar-next]').click()
        await expect(page.locator('[data-calendar-title]')).to_have_text("December 2026")
        christmas_bars = page.locator('.calendar-event-span:has-text("Christmas")')
        await expect(christmas_bars).to_have_count(5)
        bar_box = await christmas_bars.first.bounding_box()
        day_box = await page.locator('[data-calendar-date="2026-12-01"]').bounding_box()
        assert bar_box["width"] > day_box["width"] * 4.5
        start_cell = page.locator('[data-calendar-date="2026-12-24"]')
        end_cell = page.locator('[data-calendar-date="2026-12-26"]')
        start_box, end_box = await start_cell.bounding_box(), await end_cell.bounding_box()
        await page.mouse.move(start_box["x"] + 12, start_box["y"] + 12); await page.mouse.down()
        await page.mouse.move(end_box["x"] + 12, end_box["y"] + 12, steps=12); await page.mouse.up()
        await expect(schedule_form.locator('input[name="starts_at"]')).to_have_value("2026-12-24T00:00")
        await schedule_form.locator('input[name="name"]').fill("Holiday premiere")
        await schedule_form.locator('select[name="collection_id"]').select_option(christmas_value)
        await schedule_form.locator('input[name="priority"]').fill("10")
        await schedule_form.locator('select[name="overlap_policy"]').select_option("exclusive")
        await schedule_form.locator('input[name="color"]').fill("#f59e0b")
        await schedule_form.locator('button.primary').click()
        await expect(page.locator('#schedule')).to_have_class(re.compile("active"))
        await page.locator('[data-calendar-next]').click()
        await expect(page.locator('[data-calendar-title]')).to_have_text("December 2026")
        inspector = page.locator('[data-inspector-form]')
        await inspector.locator('input[name="at"]').fill("2026-12-25T12:00")
        await inspector.locator('button[type="submit"]').click()
        await expect(page.locator('[data-inspector-explanation]')).to_contain_text("Exclusive priority 10")
        await page.wait_for_timeout(1800)
        end_handle = page.locator('.calendar-event:has-text("Holiday premiere") .event-handle.end').first
        target_cell = page.locator('[data-calendar-date="2026-12-27"]')
        await target_cell.scroll_into_view_if_needed()
        handle_box, target_box = await end_handle.bounding_box(), await target_cell.bounding_box()
        await page.mouse.move(handle_box["x"] + handle_box["width"] / 2, handle_box["y"] + handle_box["height"] / 2); await page.mouse.down()
        await page.mouse.move(target_box["x"] + 12, target_box["y"] + 12, steps=8); await page.mouse.up()
        await page.wait_for_timeout(700)
        await page.locator('.calendar-event:has-text("Holiday premiere")').first.click()
        await expect(page.locator('#edit-schedule-dialog')).to_be_visible()
        await expect(page.locator('#edit-schedule-dialog input[name="ends_at"]')).to_have_value("2026-12-28T00:00")
        await page.wait_for_timeout(900)
        await page.locator('#edit-schedule-dialog [data-close]').click()
        await page.locator('[data-tab="library"]').click()
        await page.locator('.explorer-item[data-path="Christmas"]').dblclick()
        await expect(page.locator('.collection-tag')).to_have_text("Christmas")
        await page.wait_for_timeout(1200)
        await page.locator('[data-tab="schedule"]').click()
        await page.wait_for_timeout(1200)
        await page.screenshot(path=output / "desktop.png", full_page=True)
        await context.close()

        mobile = await browser.new_context(viewport={"width": 412, "height": 915}, is_mobile=True, has_touch=True)
        mobile_page = await mobile.new_page()
        await mobile_page.goto("http://127.0.0.1:18080/", wait_until="networkidle")
        await mobile_page.locator('.explorer-item[data-path="Christmas"]').click()
        await mobile_page.locator("[data-select-mode]").click()
        await mobile_page.locator(".explorer-item").first.click()
        await expect(mobile_page.locator("[data-selection-count]")).to_have_text("1 selected")
        await mobile_page.screenshot(path=output / "mobile.png", full_page=True)
        await mobile_page.locator("[data-selection-done]").click(force=True)
        await mobile.close()
        await browser.close()


if __name__ == "__main__":
    asyncio.run(main())
